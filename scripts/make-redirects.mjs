// Writes public/_redirects (Cloudflare Pages / Netlify format) from the same data the site uses.
// Runs automatically before `npm run build` (npm "prebuild" hook), so the redirects can never drift from the forms list.
//
// Why: the old site used *.html URLs and /assets/docs/*.pdf. Every old URL gets a permanent (301) redirect so that
// search rankings, bookmarks and links from other sites carry over to the new URLs.
import fs from 'node:fs';
import path from 'node:path';
import { forms } from '../src/data/forms.ts';

const pages = [
  ['/index.html', '/'],
  ['/services.html', '/services/'],
  ['/rejuvenation.html', '/rejuvenation/'],
  ['/physicians.html', '/doctors/'],
  ['/forms.html', '/forms/'],
  ['/healthinfo.html', '/health-info/'],
  ['/contact.html', '/contact/'],
];

const lines = [
  '# Permanent redirects from the old site (generated by scripts/make-redirects.mjs. Edit the script, not this file).',
  '# Format: <old path> <new path> <status>',
  '',
  '# Old pages',
  ...pages.map(([from, to]) => `${from} ${to} 301`),
  '',
  '# Old logo path (in case another site embeds it)',
  '/assets/images/logo/pcmc2022logo.png /images/logo/pcmc2022logo.png 301',
  '',
  '# Old form downloads. Spaces are percent-encoded.',
  ...forms.map((form) => `/assets/docs/${encodeURIComponent(form.legacyFile)} /forms/${form.file} 301`),
  '',
];

const target = path.join(process.cwd(), 'public', '_redirects');
fs.writeFileSync(target, lines.join('\n'));
console.log(`wrote ${path.relative(process.cwd(), target)} (${pages.length + forms.length + 1} rules)`);
